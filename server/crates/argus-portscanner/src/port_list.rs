/// 获取指定模板的端口列表
pub fn get_ports_by_template(template: &PortTemplate) -> Vec<u16> {
    match template {
        PortTemplate::Top100 => top100_tcp_ports(),
        PortTemplate::Top1000 => top1000_tcp_ports(),
        PortTemplate::Full => (1..=65535).collect(),
        PortTemplate::Custom(ports) => ports.clone(),
    }
}

