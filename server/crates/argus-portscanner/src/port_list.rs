//! 端口列表与模板管理

use serde::{Deserialize, Serialize};
use std::collections::HashSet;

/// 常用端口模板
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum PortTemplate {
    /// Top 100 常用端口
    Top100,
    /// Top 1000 常用端口
    Top1000,
    /// 全部端口 (1-65535)
    Full,
    /// 自定义端口列表
    Custom(Vec<u16>),
}

/// 解析端口范围字符串，如 "1-100,443,8080-9090"
pub fn parse_port_range(input: &str) -> Result<Vec<u16>, String> {
    let mut ports = HashSet::new();
    for part in input.split(',') {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        if let Some((start, end)) = part.split_once('-') {
            let start: u16 = start.trim().parse().map_err(|_| format!("无效端口: {}", start))?;
            let end: u16 = end.trim().parse().map_err(|_| format!("无效端口: {}", end))?;
            if start > end {
                return Err(format!("端口范围无效: {}-{}", start, end));
            }
            for p in start..=end {
                ports.insert(p);
            }
        } else {
            let port: u16 = part.parse().map_err(|_| format!("无效端口: {}", part))?;
            ports.insert(port);
        }
    }
    let mut result: Vec<u16> = ports.into_iter().collect();
    result.sort_unstable();
    Ok(result)
}

